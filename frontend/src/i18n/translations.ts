export type UiTextKey = keyof typeof UI_TEXT.uz;

export function translate(
  lang: AppLanguage,
  key: UiTextKey,
  params?: Record<string, string | number>,
): string {
  const table = UI_TEXT[lang] ?? UI_TEXT.uz;
  let text: string = table[key] ?? UI_TEXT.uz[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function navLabel(lang: AppLanguage, view: string): string {
  const key = `nav.${view}` as UiTextKey;
  return translate(lang, key);
}

export function navMobileLabel(lang: AppLanguage, view: string, fallback: string): string {
  const key = `navMobile.${view}` as UiTextKey;
  const table = UI_TEXT[lang] ?? UI_TEXT.uz;
  if (key in table) return translate(lang, key);
  return fallback.split('(')[0]?.trim().slice(0, 11) ?? fallback;
}

export function roleLabel(lang: AppLanguage, role: string): string {
  const key = `role.${role}` as UiTextKey;
  if (key in UI_TEXT.uz) return translate(lang, key);
  return role;
}
